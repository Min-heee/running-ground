import { useMemo } from 'react';
import {
  buildLiveMatchMetricLabels,
  buildLiveMatchTrackingViewProps,
  type LiveMatchTrackingInputProps,
  type LiveMatchTrackingViewProps,
} from '@/features/runs/viewModels/liveMatchTrackingViewModel';

export type {
  LiveMatchTrackingInputProps,
  LiveMatchTrackingViewProps,
};

export function useLiveMatchTrackingViewProps({
  elapsedSeconds,
  distanceKm,
  averagePace,
  currentPace,
  cadenceSpm,
  elevationGainM,
  useLiveTrackingMetrics,
  matchMode,
  goalKmOverride,
  liveMatchTitle,
  liveMatchText,
  effectiveDuelOpponent,
  duelDistanceKm,
  duelLiveTitle,
  duelLiveSummary,
  duelStatusAlert,
  isLeavingDuelMatch,
  effectiveGroupParticipantCount,
  currentGroupStanding,
  groupAheadParticipant,
  groupBehindParticipant,
  groupStatusAlert,
  isLeavingGroupMatch,
  groupLiveStandings,
  currentGroupLeader,
  onContinueSoloFromMatch,
}: LiveMatchTrackingInputProps) {
  const metricLabels = useMemo(() => buildLiveMatchMetricLabels({
    elapsedSeconds,
    distanceKm,
    averagePace,
    currentPace,
    cadenceSpm,
    elevationGainM,
  }), [
    averagePace,
    cadenceSpm,
    currentPace,
    distanceKm,
    elapsedSeconds,
    elevationGainM,
  ]);

  const input = useMemo<LiveMatchTrackingInputProps>(() => ({
    matchMode,
    goalKmOverride,
    liveMatchTitle,
    liveMatchText,
    effectiveDuelOpponent,
    duelDistanceKm,
    duelLiveTitle,
    duelLiveSummary,
    duelStatusAlert,
    distanceKm,
    isLeavingDuelMatch,
    effectiveGroupParticipantCount,
    currentGroupStanding,
    groupAheadParticipant,
    groupBehindParticipant,
    groupStatusAlert,
    isLeavingGroupMatch,
    groupLiveStandings,
    currentGroupLeader,
    elapsedSeconds,
    averagePace,
    currentPace,
    cadenceSpm,
    elevationGainM,
    useLiveTrackingMetrics,
    onContinueSoloFromMatch,
  }), [
    averagePace,
    cadenceSpm,
    currentGroupLeader,
    currentGroupStanding,
    currentPace,
    distanceKm,
    duelDistanceKm,
    duelLiveSummary,
    duelLiveTitle,
    duelStatusAlert,
    effectiveDuelOpponent,
    effectiveGroupParticipantCount,
    elapsedSeconds,
    elevationGainM,
    goalKmOverride,
    groupAheadParticipant,
    groupBehindParticipant,
    groupLiveStandings,
    groupStatusAlert,
    isLeavingDuelMatch,
    isLeavingGroupMatch,
    liveMatchText,
    liveMatchTitle,
    matchMode,
    onContinueSoloFromMatch,
    useLiveTrackingMetrics,
  ]);

  return useMemo<LiveMatchTrackingViewProps>(() => (
    buildLiveMatchTrackingViewProps({ metricLabels, input })
  ), [input, metricLabels]);
}
