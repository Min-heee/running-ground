import { useMemo } from 'react';
import type {
  LiveMatchMetricLabels,
  LiveMatchTrackingPageProps,
} from '@/features/runs/components/LiveMatchTrackingPage';
import { formatDuration } from '@/features/runs/tracking';
import {
  formatCadence,
  formatElevation,
  formatMetricDistance,
} from '@/features/runs/tracking/trackingSession';

export type LiveMatchTrackingInputProps = Omit<LiveMatchTrackingPageProps, 'includeMatchCards' | 'metricLabels'>;
export type LiveMatchTrackingViewProps = Omit<LiveMatchTrackingPageProps, 'includeMatchCards'>;

export function useLiveMatchTrackingViewProps({
  elapsedSeconds,
  distanceKm,
  averagePace,
  currentPace,
  cadenceSpm,
  elevationGainM,
  matchMode,
  liveMatchTitle,
  liveMatchText,
  effectiveDuelOpponent,
  duelDistanceKm,
  duelLiveTitle,
  duelLiveSummary,
  duelStatusAlert,
  isLeavingDuelMatch,
  effectiveGroupParticipantCount,
  currentGroupStanding,
  groupAheadParticipant,
  groupBehindParticipant,
  groupStatusAlert,
  isLeavingGroupMatch,
  groupLiveStandings,
  currentGroupLeader,
  onContinueSoloFromMatch,
}: LiveMatchTrackingInputProps) {
  const metricLabels = useMemo<LiveMatchMetricLabels>(() => ({
    elapsedLabel: formatDuration(elapsedSeconds),
    distanceLabel: formatMetricDistance(distanceKm),
    averagePaceLabel: averagePace,
    currentPaceLabel: currentPace,
    cadenceLabel: formatCadence(cadenceSpm),
    elevationLabel: formatElevation(elevationGainM),
  }), [
    averagePace,
    cadenceSpm,
    currentPace,
    distanceKm,
    elapsedSeconds,
    elevationGainM,
  ]);

  return useMemo<LiveMatchTrackingViewProps>(() => ({
    matchMode,
    liveMatchTitle,
    liveMatchText,
    effectiveDuelOpponent,
    duelDistanceKm,
    duelLiveTitle,
    duelLiveSummary,
    duelStatusAlert,
    distanceKm,
    isLeavingDuelMatch,
    effectiveGroupParticipantCount,
    currentGroupStanding,
    groupAheadParticipant,
    groupBehindParticipant,
    groupStatusAlert,
    isLeavingGroupMatch,
    groupLiveStandings,
    currentGroupLeader,
    elapsedSeconds,
    averagePace,
    currentPace,
    cadenceSpm,
    elevationGainM,
    metricLabels,
    onContinueSoloFromMatch,
  }), [
    averagePace,
    cadenceSpm,
    currentGroupLeader,
    currentGroupStanding,
    currentPace,
    distanceKm,
    duelDistanceKm,
    duelLiveSummary,
    duelLiveTitle,
    duelStatusAlert,
    effectiveDuelOpponent,
    effectiveGroupParticipantCount,
    elapsedSeconds,
    elevationGainM,
    groupAheadParticipant,
    groupBehindParticipant,
    groupLiveStandings,
    groupStatusAlert,
    isLeavingDuelMatch,
    isLeavingGroupMatch,
    liveMatchText,
    liveMatchTitle,
    matchMode,
    metricLabels,
    onContinueSoloFromMatch,
  ]);
}
