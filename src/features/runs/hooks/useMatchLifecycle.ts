import { useState } from 'react';
import {
  useDuelMatchLifecycle,
  useGroupMatchLifecycle,
  useMatchDemandSummary,
  useMatchQueueActions,
  type RunMatchMode,
} from '@/features/runs/hooks/matchLifecycle';

export type { RunMatchMode } from '@/features/runs/hooks/matchLifecycle';

type TestFlowInput = {
  focusMatchMode?: Extract<RunMatchMode, 'duel' | 'group'>;
  focusMatchIsTest?: boolean;
};

export function useMatchLifecycle({ focusMatchMode, focusMatchIsTest }: TestFlowInput) {
  const [matchMode, setMatchMode] = useState<RunMatchMode>('duel');
  const focusRequestedDuelTest = focusMatchMode === 'duel' && focusMatchIsTest === true;
  const focusRequestedGroupTest = focusMatchMode === 'group' && focusMatchIsTest === true;
  const queueActions = useMatchQueueActions();
  const demandSummary = useMatchDemandSummary();
  const duelLifecycle = useDuelMatchLifecycle({
    initialMatchSlot: queueActions.initialMatchSlot,
    slotOptions: queueActions.weeklyMatchSlotOptions,
    focusRequestedTest: focusRequestedDuelTest,
    matchMode,
  });
  const groupLifecycle = useGroupMatchLifecycle({
    initialMatchSlot: queueActions.initialMatchSlot,
    slotOptions: queueActions.weeklyMatchSlotOptions,
    focusRequestedTest: focusRequestedGroupTest,
    matchMode,
  });

  return {
    matchMode,
    setMatchMode,
    duelDistanceText: duelLifecycle.duelDistanceText,
    setDuelDistanceText: duelLifecycle.setDuelDistanceText,
    showDuelCustomDistanceInput: duelLifecycle.showDuelCustomDistanceInput,
    setShowDuelCustomDistanceInput: duelLifecycle.setShowDuelCustomDistanceInput,
    selectedDuelSlotStartAt: duelLifecycle.selectedDuelSlotStartAt,
    setSelectedDuelSlotStartAt: duelLifecycle.setSelectedDuelSlotStartAt,
    selectedDuelDateKey: duelLifecycle.selectedDuelDateKey,
    setSelectedDuelDateKey: duelLifecycle.setSelectedDuelDateKey,
    selectedDuelTimeSection: duelLifecycle.selectedDuelTimeSection,
    setSelectedDuelTimeSection: duelLifecycle.setSelectedDuelTimeSection,
    isRequestingDuelMatch: duelLifecycle.isRequestingDuelMatch,
    setIsRequestingDuelMatch: duelLifecycle.setIsRequestingDuelMatch,
    duelMatchResult: duelLifecycle.duelMatchResult,
    setDuelMatchResult: duelLifecycle.setDuelMatchResult,
    duelMatchStatus: duelLifecycle.duelMatchStatus,
    setDuelMatchStatus: duelLifecycle.setDuelMatchStatus,
    isCancelingDuelMatch: duelLifecycle.isCancelingDuelMatch,
    setIsCancelingDuelMatch: duelLifecycle.setIsCancelingDuelMatch,
    isLeavingDuelMatch: duelLifecycle.isLeavingDuelMatch,
    setIsLeavingDuelMatch: duelLifecycle.setIsLeavingDuelMatch,
    duelDemandSummary: demandSummary.duelDemandSummary,
    setDuelDemandSummary: demandSummary.setDuelDemandSummary,
    isLoadingDuelDemandSummary: demandSummary.isLoadingDuelDemandSummary,
    setIsLoadingDuelDemandSummary: demandSummary.setIsLoadingDuelDemandSummary,
    duelMatchNotice: duelLifecycle.duelMatchNotice,
    setDuelMatchNotice: duelLifecycle.setDuelMatchNotice,
    groupDistanceText: groupLifecycle.groupDistanceText,
    setGroupDistanceText: groupLifecycle.setGroupDistanceText,
    showGroupCustomDistanceInput: groupLifecycle.showGroupCustomDistanceInput,
    setShowGroupCustomDistanceInput: groupLifecycle.setShowGroupCustomDistanceInput,
    selectedGroupSlotStartAt: groupLifecycle.selectedGroupSlotStartAt,
    setSelectedGroupSlotStartAt: groupLifecycle.setSelectedGroupSlotStartAt,
    selectedGroupDateKey: groupLifecycle.selectedGroupDateKey,
    setSelectedGroupDateKey: groupLifecycle.setSelectedGroupDateKey,
    selectedGroupTimeSection: groupLifecycle.selectedGroupTimeSection,
    setSelectedGroupTimeSection: groupLifecycle.setSelectedGroupTimeSection,
    isRequestingGroupMatch: groupLifecycle.isRequestingGroupMatch,
    setIsRequestingGroupMatch: groupLifecycle.setIsRequestingGroupMatch,
    groupMatchResult: groupLifecycle.groupMatchResult,
    setGroupMatchResult: groupLifecycle.setGroupMatchResult,
    groupMatchStatus: groupLifecycle.groupMatchStatus,
    setGroupMatchStatus: groupLifecycle.setGroupMatchStatus,
    isCancelingGroupMatch: groupLifecycle.isCancelingGroupMatch,
    setIsCancelingGroupMatch: groupLifecycle.setIsCancelingGroupMatch,
    isLeavingGroupMatch: groupLifecycle.isLeavingGroupMatch,
    setIsLeavingGroupMatch: groupLifecycle.setIsLeavingGroupMatch,
    groupDemandSummary: demandSummary.groupDemandSummary,
    setGroupDemandSummary: demandSummary.setGroupDemandSummary,
    isLoadingGroupDemandSummary: demandSummary.isLoadingGroupDemandSummary,
    setIsLoadingGroupDemandSummary: demandSummary.setIsLoadingGroupDemandSummary,
    groupMatchNotice: groupLifecycle.groupMatchNotice,
    setGroupMatchNotice: groupLifecycle.setGroupMatchNotice,
    upcomingMatches: queueActions.upcomingMatches,
    setUpcomingMatches: queueActions.setUpcomingMatches,
    duelSlotCounts: queueActions.duelSlotCounts,
    setDuelSlotCounts: queueActions.setDuelSlotCounts,
    matchRemindersEnabled: queueActions.matchRemindersEnabled,
    setMatchRemindersEnabled: queueActions.setMatchRemindersEnabled,
    cancelingUpcomingMatchId: queueActions.cancelingUpcomingMatchId,
    setCancelingUpcomingMatchId: queueActions.setCancelingUpcomingMatchId,
    nowMs: queueActions.nowMs,
    setNowMs: queueActions.setNowMs,
    serverClockOffsetMs: queueActions.serverClockOffsetMs,
    syncedNowMs: queueActions.syncedNowMs,
    serverClockOffsetMsRef: queueActions.serverClockOffsetMsRef,
    syncServerClock: queueActions.syncServerClock,
    getSyncedNowMs: queueActions.getSyncedNowMs,
    liveArenaPage: queueActions.liveArenaPage,
    setLiveArenaPage: queueActions.setLiveArenaPage,
    forceOpenActiveMatch: queueActions.forceOpenActiveMatch,
    setForceOpenActiveMatch: queueActions.setForceOpenActiveMatch,
    isResolvingFocusedMatch: queueActions.isResolvingFocusedMatch,
    setIsResolvingFocusedMatch: queueActions.setIsResolvingFocusedMatch,
    duelDistanceKm: duelLifecycle.duelDistanceKm,
    groupDistanceKm: groupLifecycle.groupDistanceKm,
    duelSlotOptions: duelLifecycle.duelSlotOptions,
    groupSlotOptions: groupLifecycle.groupSlotOptions,
    duelDateOptions: duelLifecycle.duelDateOptions,
    groupDateOptions: groupLifecycle.groupDateOptions,
    selectedDuelSlot: duelLifecycle.selectedDuelSlot,
    selectedGroupSlot: groupLifecycle.selectedGroupSlot,
    visibleDuelSlotOptions: duelLifecycle.visibleDuelSlotOptions,
    visibleGroupSlotOptions: groupLifecycle.visibleGroupSlotOptions,
    activeDuelSlotStartAt: duelLifecycle.activeDuelSlotStartAt,
    activeGroupSlotStartAt: groupLifecycle.activeGroupSlotStartAt,
    duelMatchState: duelLifecycle.duelMatchState,
    groupMatchState: groupLifecycle.groupMatchState,
    focusRequestedDuelTest,
    focusRequestedGroupTest,
    isDuelTestFlow: duelLifecycle.isDuelTestFlow,
    isGroupTestFlow: groupLifecycle.isGroupTestFlow,
    effectiveGroupParticipants: groupLifecycle.effectiveGroupParticipants,
    effectiveGroupParticipantCount: groupLifecycle.effectiveGroupParticipantCount,
    effectiveGroupSeedRank: groupLifecycle.effectiveGroupSeedRank,
    selectNextDuelSlotForDate: duelLifecycle.selectNextDuelSlotForDate,
    selectNextGroupSlotForDate: groupLifecycle.selectNextGroupSlotForDate,
    selectDuelTimeSection: duelLifecycle.selectDuelTimeSection,
    selectGroupTimeSection: groupLifecycle.selectGroupTimeSection,
  };
}
