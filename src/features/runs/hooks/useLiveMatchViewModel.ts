import { useMemo } from 'react';
import type { RefObject } from 'react';
import type { ScrollView } from 'react-native';
import type {
  LiveMatchArenaPageProps,
} from '@/features/runs/components/LiveMatchArenaPage';
import type {
  LiveMatchPagesProps,
} from '@/features/runs/components/LiveMatchPages';
import type {
  LiveMatchRaceBoardPageProps,
} from '@/features/runs/components/LiveMatchRaceBoardPage';
import type {
  LiveMatchResultPageProps,
} from '@/features/runs/components/LiveMatchResultPage';
import type {
  LiveMatchTrackingPageProps,
} from '@/features/runs/components/LiveMatchTrackingPage';

type LiveMatchTrackingBaseProps = Omit<LiveMatchTrackingPageProps, 'includeMatchCards'>;

type UseLiveMatchViewModelInput =
  LiveMatchArenaPageProps
  & LiveMatchRaceBoardPageProps
  & LiveMatchTrackingBaseProps
  & LiveMatchResultPageProps
  & {
    scrollRef: RefObject<ScrollView | null>;
    page: number;
    pageWidth: number;
    hasResultPage: boolean;
    onPageChange: (page: number) => void;
  };

export function useLiveMatchViewModel({
  scrollRef,
  page,
  pageWidth,
  hasResultPage,
  onPageChange,
  activeMatchId,
  matchMode,
  effectiveDuelOpponent,
  duelDistanceKm,
  groupDistanceKm,
  distanceKm,
  duelLiveSummary,
  currentUserArenaPace,
  isDuelOpponentForfeited,
  effectiveDuelOpponentArenaPace,
  duelComparisonSnapshot,
  officialDuelReady,
  duelLiveGapKm,
  duelArenaParticipants,
  syncedDuelDistanceKm,
  syncedDuelOpponentDistanceKm,
  roomLinkedDuelPlaceholderParticipants,
  roomLinkedDuelCurrentParticipant,
  roomLinkedDuelOpponentParticipant,
  roomLinkedGroupPlaceholderParticipants,
  visibleMatchRoom,
  roomCountdownRemainingSeconds,
  duelArenaUsesLivePace,
  hasRoomLinkedDuelLiveProgress,
  roomLinkedDuelGapKm,
  currentGroupStanding,
  effectiveGroupParticipantCount,
  currentGroupLeader,
  groupArenaParticipants,
  groupAheadParticipant,
  groupBehindParticipant,
  shouldKeepRunningMatchArena,
  currentUserDuelLiveStatus,
  currentUserGroupLiveStatus,
  deferHeavyContent,
  onLiveMatchMounted,
  groupLiveStandings,
  groupArenaUsesLivePace,
  liveMatchTitle,
  liveMatchText,
  duelLiveTitle,
  duelStatusAlert,
  isLeavingDuelMatch,
  groupStatusAlert,
  isLeavingGroupMatch,
  elapsedSeconds,
  averagePace,
  currentPace,
  cadenceSpm,
  elevationGainM,
  onContinueSoloFromMatch,
  estimatedBonusPoints,
  duelRows,
  groupRows,
  groupStatusLabel,
}: UseLiveMatchViewModelInput) {
  const arenaProps = useMemo<LiveMatchArenaPageProps>(() => ({
    activeMatchId,
    matchMode,
    effectiveDuelOpponent,
    duelDistanceKm,
    groupDistanceKm,
    distanceKm,
    duelLiveSummary,
    currentUserArenaPace,
    isDuelOpponentForfeited,
    effectiveDuelOpponentArenaPace,
    duelComparisonSnapshot,
    officialDuelReady,
    duelLiveGapKm,
    duelArenaParticipants,
    syncedDuelDistanceKm,
    syncedDuelOpponentDistanceKm,
    roomLinkedDuelPlaceholderParticipants,
    roomLinkedDuelCurrentParticipant,
    roomLinkedDuelOpponentParticipant,
    roomLinkedGroupPlaceholderParticipants,
    visibleMatchRoom,
    roomCountdownRemainingSeconds,
    duelArenaUsesLivePace,
    hasRoomLinkedDuelLiveProgress,
    roomLinkedDuelGapKm,
    currentGroupStanding,
    effectiveGroupParticipantCount,
    currentGroupLeader,
    groupArenaParticipants,
    groupAheadParticipant,
    groupBehindParticipant,
    shouldKeepRunningMatchArena,
    currentUserDuelLiveStatus,
    currentUserGroupLiveStatus,
    deferHeavyContent,
    onLiveMatchMounted,
  }), [
    activeMatchId,
    currentGroupLeader,
    currentGroupStanding,
    currentUserArenaPace,
    currentUserDuelLiveStatus,
    currentUserGroupLiveStatus,
    deferHeavyContent,
    distanceKm,
    duelArenaParticipants,
    duelArenaUsesLivePace,
    duelComparisonSnapshot,
    duelDistanceKm,
    duelLiveGapKm,
    duelLiveSummary,
    effectiveDuelOpponent,
    effectiveDuelOpponentArenaPace,
    effectiveGroupParticipantCount,
    groupAheadParticipant,
    groupArenaParticipants,
    groupBehindParticipant,
    groupDistanceKm,
    hasRoomLinkedDuelLiveProgress,
    isDuelOpponentForfeited,
    matchMode,
    officialDuelReady,
    onLiveMatchMounted,
    roomCountdownRemainingSeconds,
    roomLinkedDuelCurrentParticipant,
    roomLinkedDuelGapKm,
    roomLinkedDuelOpponentParticipant,
    roomLinkedDuelPlaceholderParticipants,
    roomLinkedGroupPlaceholderParticipants,
    shouldKeepRunningMatchArena,
    syncedDuelDistanceKm,
    syncedDuelOpponentDistanceKm,
    visibleMatchRoom,
  ]);

  const raceBoardProps = useMemo<LiveMatchRaceBoardPageProps>(() => ({
    matchMode,
    effectiveDuelOpponent,
    duelLiveGapKm,
    duelDistanceKm,
    groupDistanceKm,
    distanceKm,
    syncedDuelDistanceKm,
    syncedDuelOpponentDistanceKm,
    currentUserDuelLiveStatus,
    currentUserGroupLiveStatus,
    roomLinkedDuelPlaceholderParticipants,
    roomLinkedGroupPlaceholderParticipants,
    visibleMatchRoom,
    groupLiveStandings,
    currentUserArenaPace,
    groupArenaUsesLivePace,
  }), [
    currentUserArenaPace,
    currentUserDuelLiveStatus,
    currentUserGroupLiveStatus,
    distanceKm,
    duelDistanceKm,
    duelLiveGapKm,
    effectiveDuelOpponent,
    groupArenaUsesLivePace,
    groupDistanceKm,
    groupLiveStandings,
    matchMode,
    roomLinkedDuelPlaceholderParticipants,
    roomLinkedGroupPlaceholderParticipants,
    syncedDuelDistanceKm,
    syncedDuelOpponentDistanceKm,
    visibleMatchRoom,
  ]);

  const trackingPageProps = useMemo<LiveMatchTrackingBaseProps>(() => ({
    matchMode,
    liveMatchTitle,
    liveMatchText,
    effectiveDuelOpponent,
    duelDistanceKm,
    duelLiveTitle,
    duelLiveSummary,
    duelStatusAlert,
    distanceKm,
    isLeavingDuelMatch,
    effectiveGroupParticipantCount,
    currentGroupStanding,
    groupAheadParticipant,
    groupBehindParticipant,
    groupStatusAlert,
    isLeavingGroupMatch,
    groupLiveStandings,
    currentGroupLeader,
    elapsedSeconds,
    averagePace,
    currentPace,
    cadenceSpm,
    elevationGainM,
    onContinueSoloFromMatch,
  }), [
    averagePace,
    cadenceSpm,
    currentGroupLeader,
    currentGroupStanding,
    currentPace,
    distanceKm,
    duelDistanceKm,
    duelLiveSummary,
    duelLiveTitle,
    duelStatusAlert,
    effectiveDuelOpponent,
    effectiveGroupParticipantCount,
    elapsedSeconds,
    elevationGainM,
    groupAheadParticipant,
    groupBehindParticipant,
    groupLiveStandings,
    groupStatusAlert,
    isLeavingDuelMatch,
    isLeavingGroupMatch,
    liveMatchText,
    liveMatchTitle,
    matchMode,
    onContinueSoloFromMatch,
  ]);

  const resultProps = useMemo<LiveMatchResultPageProps>(() => ({
    matchMode,
    estimatedBonusPoints,
    duelRows,
    groupRows,
    groupStatusLabel,
  }), [
    duelRows,
    estimatedBonusPoints,
    groupRows,
    groupStatusLabel,
    matchMode,
  ]);

  const livePagesProps = useMemo<Omit<LiveMatchPagesProps, 'exitAction'>>(() => ({
    scrollRef,
    page,
    pageWidth,
    hasResultPage,
    arenaProps,
    raceBoardProps: page === 1 ? raceBoardProps : null,
    trackingProps: page === 2 ? { ...trackingPageProps, includeMatchCards: false } : null,
    resultProps: page === 3 ? resultProps : null,
    onPageChange,
  }), [
    arenaProps,
    hasResultPage,
    onPageChange,
    page,
    pageWidth,
    raceBoardProps,
    resultProps,
    scrollRef,
    trackingPageProps,
  ]);

  return {
    livePagesProps,
    trackingPageProps,
  };
}
